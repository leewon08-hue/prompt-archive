create table if not exists public.prompts (
 id bigint generated by default as identity primary key,
 category text not null check (category in ('persona','action')),
 title text not null,
 body text not null,
 image_url text,
 created_at timestamptz not null default now()
);
alter table public.prompts add column if not exists image_url text;
alter table public.prompts enable row level security;

create policy "Public can read prompts" on public.prompts for select to anon, authenticated using (true);
create policy "Admin can insert prompts" on public.prompts for insert to authenticated
with check ((auth.jwt()->>'email')='YOUR_ADMIN_EMAIL');
create policy "Admin can update prompts" on public.prompts for update to authenticated
using ((auth.jwt()->>'email')='YOUR_ADMIN_EMAIL')
with check ((auth.jwt()->>'email')='YOUR_ADMIN_EMAIL');
create policy "Admin can delete prompts" on public.prompts for delete to authenticated
using ((auth.jwt()->>'email')='YOUR_ADMIN_EMAIL');

-- Public image view; admin-only upload/update/delete. Replace email placeholder above and below.
insert into storage.buckets(id,name,public) values('prompt-images','prompt-images',true)
on conflict(id) do update set public=true;
create policy "Public can view prompt images" on storage.objects for select to anon,authenticated
using(bucket_id='prompt-images');
create policy "Admin can upload prompt images" on storage.objects for insert to authenticated
with check(bucket_id='prompt-images' and (storage.foldername(name))[1]=auth.uid()::text and (auth.jwt()->>'email')='YOUR_ADMIN_EMAIL');
create policy "Admin can update prompt images" on storage.objects for update to authenticated
using(bucket_id='prompt-images' and (storage.foldername(name))[1]=auth.uid()::text and (auth.jwt()->>'email')='YOUR_ADMIN_EMAIL')
with check(bucket_id='prompt-images' and (storage.foldername(name))[1]=auth.uid()::text and (auth.jwt()->>'email')='YOUR_ADMIN_EMAIL');
create policy "Admin can delete prompt images" on storage.objects for delete to authenticated
using(bucket_id='prompt-images' and (storage.foldername(name))[1]=auth.uid()::text and (auth.jwt()->>'email')='YOUR_ADMIN_EMAIL');
